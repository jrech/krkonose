// Builds the "Běžný svoz" zone in src/data/service-area-zone.ts: a convex hull around the places the
// owner confirmed, grown by BUFFER_KM so the countryside between and around them counts too.
// Run: node tools/service-area/build-zone.mjs   (no dependencies, no network)
//
// Coordinates: Mapy.com suggest API (municipality centres), 2026-10-24. Horní Mísečky and Skelné Hutě
// have no entry there; they are approximate settlement centres and sit well inside the hull anyway.
import { writeFileSync } from 'node:fs';

const BUFFER_KM = 2.5;
const SEGMENTS = 24;

/** [name, lat, lon] — the owner's "ano" list. */
const places = [
  ['Vrchlabí', 50.6270, 15.6094],
  ['Pec pod Sněžkou', 50.6934, 15.7331],
  ['Janské Lázně', 50.6311, 15.7818],
  ['Horní Maršov', 50.6586, 15.8198],
  ['Svoboda nad Úpou', 50.6260, 15.8165],
  ['Rudník', 50.5784, 15.7373],
  ['Mladé Buky', 50.6064, 15.8335],
  ['Jilemnice', 50.6089, 15.5065],
  ['Černý Důl', 50.6350, 15.7106],
  ['Dolní Dvůr', 50.6523, 15.6556],
  ['Lánov', 50.6350, 15.6589],
  ['Hostinné', 50.5407, 15.7233],
  ['Rokytnice nad Jizerou', 50.7256, 15.4336],
  ['Špindlerův Mlýn', 50.7261, 15.6094],
  ['Horní Branná', 50.6080, 15.5701],
  ['Benecko', 50.6663, 15.5482],
  ['Poniklá', 50.6615, 15.4633],
  ['Jestřabí v Krkonoších', 50.6805, 15.4917],
  ['Horní Mísečky', 50.7370, 15.5530],
  ['Vítkovice', 50.6850, 15.5243],
  ['Skelné Hutě', 50.7000, 15.5100],
  ['Františkov', 50.7161, 15.4821],
];

// Local flat projection in km (fine for a ~30 km area).
const REF_LAT = 50.65;
const KM_LAT = 111.32;
const KM_LON = 111.32 * Math.cos((REF_LAT * Math.PI) / 180);
const toKm = ([lat, lon]) => [lon * KM_LON, lat * KM_LAT];
const toLngLat = ([x, y]) => [+(x / KM_LON).toFixed(5), +(y / KM_LAT).toFixed(5)];

const ring = places.flatMap(([, lat, lon]) => {
  const [x, y] = toKm([lat, lon]);
  return Array.from({ length: SEGMENTS }, (_, i) => {
    const a = (2 * Math.PI * i) / SEGMENTS;
    return [x + BUFFER_KM * Math.cos(a), y + BUFFER_KM * Math.sin(a)];
  });
});

// Monotone chain convex hull.
function hull(points) {
  const p = [...points].sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  const cross = (o, a, b) => (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0]);
  const lower = [], upper = [];
  for (const pt of p) { while (lower.length >= 2 && cross(lower.at(-2), lower.at(-1), pt) <= 0) lower.pop(); lower.push(pt); }
  for (const pt of p.reverse()) { while (upper.length >= 2 && cross(upper.at(-2), upper.at(-1), pt) <= 0) upper.pop(); upper.push(pt); }
  return [...lower.slice(0, -1), ...upper.slice(0, -1)];
}

const outline = hull(ring).map(toLngLat);
outline.push(outline[0]);

const file = `// GENERATED by tools/service-area/build-zone.mjs — edit the place list there, not this file.
// Convex hull around the owner-confirmed places, grown by ${BUFFER_KM} km. [lng, lat], WGS 84.
import type { ServiceZone } from './service-area';

export const regularPickupZone: ServiceZone = {
  type: 'Feature',
  properties: { id: 'bezny-svoz', name: 'Běžný svoz: Vrchlabsko, Jilemnicko, Hostinné, Rokytnice, Špindl, Pec a Janské Lázně', result: 'available' },
  geometry: {
    type: 'Polygon',
    coordinates: [${JSON.stringify(outline)}],
  },
};
`;
writeFileSync(new URL('../../src/data/service-area-zone.ts', import.meta.url), file);
console.log(`service-area-zone.ts: ${outline.length - 1} vertices`);
